// ExternalBootstrap is an ordinary Job command; no database or shell is required.
func ExternalBootstrap(ctx context.Context, args []string) error {
	if len(args) != 0 {
		return errors.New("usage: /forge-init external-bootstrap")
	}
	c, err := loadExternalBootstrapConfig()
	if err != nil {
		return err
	}
	transport, err := client.NewHTTP(c.CAFile)
	if err != nil {
		return errors.New("cannot load bootstrap CA")
	}
	defer transport.CloseIdleConnections()
	store, err := bootstrap.InClusterStore(c.Namespace, c.OutputSecret)
	if err != nil {
		return err
	}
	return bootstrap.Run(ctx, c, store, transport)
}

func loadExternalBootstrapConfig() (bootstrap.Config, error) {
	snapshot, err := conf.Load("")
	if err != nil {
		return bootstrap.Config{}, errors.New("cannot load bootstrap TOML configuration")
	}
	// Decode only the sections consumed by external initialization. Database,
	// storage and credentials generated by this command are not prerequisites.
	var file struct {
		Tenant    config.TenantConfig
		Casdoor   config.CasdoorConfig
		Gitlab    config.GitlabConfig
		Bootstrap config.BootstrapConfig
	}
	if err := snapshot.Unmarshal(&file); err != nil {
		return bootstrap.Config{}, errors.New("invalid bootstrap TOML configuration")
	}
	namespace, release := os.Getenv("POD_NAMESPACE"), os.Getenv("HELM_RELEASE_NAME")
	if namespace == "" || release == "" {
		return bootstrap.Config{}, errors.New("external bootstrap requires POD_NAMESPACE and HELM_RELEASE_NAME")
	}
	identity := namespace + "-" + release
	c := bootstrap.Config{
		CasdoorURL:            strings.TrimRight(file.Casdoor.URL, "/"),
		CasdoorOrganization:   file.Casdoor.Organization,
		CasdoorCertificate:    file.Bootstrap.Certificate,
		OIDCApplication:       identity + "-console",
		ManagementApplication: identity + "-management",
		PublicURL:             strings.TrimRight(file.Tenant.PublicURL, "/"),
		BootstrapUsername:     file.Bootstrap.Username,
		BootstrapEmail:        file.Bootstrap.Email,
		GitLabURL:             strings.TrimRight(file.Gitlab.URL, "/"),
		GitLabTokenName:       identity + "-tenant",
		GitLabTokenExpiresAt:  file.Bootstrap.GitLabTokenExpiresAt,
		Namespace:             namespace,
		OutputSecret:          release + "-external-credentials",
		AdminDirectory:        bootstrap.AdminDirectory,
		SeedDirectory:         bootstrap.SeedDirectory,
		CAFile:                file.Tenant.CAFile,
	}
	return c, c.Validate()
}

// WaitExternal reads a projected Secret directory on every attempt, never subPath
// or environment values captured when Kubernetes created the init container.
func WaitExternal(ctx context.Context, args []string) error {
	flags := flag.NewFlagSet("wait-external", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	directory := flags.String("directory", bootstrap.ExternalDirectory, "projected output Secret directory")
	if err := flags.Parse(args); err != nil || flags.NArg() != 0 || strings.TrimSpace(*directory) == "" {
		return errors.New("usage: /forge-init wait-external [--directory DIR] (maximum wait 300s)")
	}
	ctx, cancel := context.WithTimeout(ctx, bootstrap.Timeout)
	defer cancel()
	timer := time.NewTicker(time.Second)
	defer timer.Stop()
	for {
		if _, err := readExternal(*directory); err == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return errors.New("timed out waiting for complete external credentials")
		case <-timer.C:
		}
	}
}

func readExternal(directory string) (map[string]string, error) {
	// Resolve Kubernetes' current ..data symlink once so marker and fields come
	// from one atomic projection. Plain directories are also useful for CLI use.
	snapshot := directory
	if resolved, err := filepath.EvalSymlinks(filepath.Join(directory, "..data")); err == nil {
		snapshot = resolved
	}
	complete, err := bootstrap.ReadCredential(snapshot, bootstrap.CompleteKey)
	if err != nil || complete != "true" {
		return nil, errors.New("external bootstrap is incomplete")
	}
	values := map[string]string{}
	for _, key := range bootstrap.RequiredKeys {
		value, err := bootstrap.ReadCredential(snapshot, key)
		if err != nil {
			return nil, err
		}
		values[key] = value
	}
	return values, nil
}

// LoadExternalEnvironment is used only by the bootstrap process, before config
// loading. Main containers obtain the completed values through envFrom.
func LoadExternalEnvironment(directory string) error {
	if strings.TrimSpace(directory) == "" {
		return nil
	}
	values, err := readExternal(directory)
	if err != nil {
		return err
	}
	for key, value := range values {
		if err := os.Setenv(key, value); err != nil {
			return err
		}
	}
	return nil
}
